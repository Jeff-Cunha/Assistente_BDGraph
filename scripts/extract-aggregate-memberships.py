"""Export a reviewed source enumeration of aggregate functions, bound to a source hash."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parents[1]


def listed_functions(quote):
    if 'aggregate functions' not in quote or 'An aggregate function computes' not in quote:
        raise ValueError('Not the expected aggregate-function explanation.')
    return re.findall(r'`([a-z]+)`', quote)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--review', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    if not args.output.resolve().is_relative_to(ROOT) or args.output.exists():
        p.error('Choose a new output file inside project.')
    review = json.loads(args.review.read_text(encoding='utf-8'))
    chunks = {c['chunk_id']: c for c in (json.loads(line) for line in
        (ROOT / 'corpus/chunks/chunks.jsonl').read_text(encoding='utf-8').splitlines())}
    c = chunks[review['chunk_id']]
    if hashlib.sha256(c['text'].encode('utf-8')).hexdigest() != review['chunk_sha256']:
        raise ValueError('Source changed; review the enumeration again.')
    start, end = review['start'], review['end']
    quote = c['text'][start:end]
    if listed_functions(quote) != review['approved_function_names']:
        raise ValueError('Enumeration differs from the reviewed list.')
    evidence = [{'chunk_id': c['chunk_id'], 'quote': quote}]
    concepts, relations = [], []
    target = review['aggregate_concept']
    for function in review['approved_function_names']:
        meta = review['function_concepts'][function]
        concepts.append({**meta, 'evidence': evidence, 'review_status': 'accepted',
                         'review_note': 'Source enumeration detected by rule and explicitly reviewed by Codex; no independent human review.'})
        relations.append({'relation_id': f'R_rule_{function}_is_a_aggregate_function',
            'source': meta['concept_id'], 'type': 'IS_A', 'target': target['concept_id'],
            'assertion_kind': 'explicit', 'evidence': evidence, 'review_status': 'accepted',
            'review_note': 'Function is listed as an aggregate in the source paragraph. Rule-derived, not generated by an LLM. No query execution or claim of complete API coverage.'})
    concepts.append({**target, 'evidence': evidence, 'review_status': 'accepted',
                     'review_note': 'Definition and function list explicitly provided by the source; Portuguese summary curated by Codex.'})
    graph = dict(schema_version='0.1.1', extraction_method='rule_candidates', input_chunk_ids=[c['chunk_id']],
                 concepts=concepts, relations=relations)
    schema = json.loads((ROOT / 'schemas/extraction.schema.json').read_text(encoding='utf-8'))
    Draft202012Validator(schema).validate(graph)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(graph, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print('Exported five reviewed rule-derived IS_A relationships and six concepts.')


if __name__ == '__main__':
    main()
